#!/usr/bin/env python3
"""Real-MDS verification of small-segment production import and reopen.

The testing library is used only to create an 8 MiB-segment empty database.
All three offline imports and the final MDS queries use the production library.
Pass the 30,000-file/6,001-directory bundle generated by
lhm_segmented_import_test.py. Every process and database is isolated and pinned.
"""

import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import shutil
import socket
import struct
import subprocess
import sys
import time
import urllib.request

from lhm_batch_recovery_test import (assert_snapshot_files, parse_segment_layout,
                                   require, segment_files, checkpoint_indexes)


SEGMENT_BYTES = 8 << 20
PAGES = SEGMENT_BYTES // 16384
WORK_DIR = None


def sha(path):
    value = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(8 << 20), b''):
            value.update(chunk)
    return value.hexdigest()


def save(path, value):
    temporary = path.with_name(path.name + '.tmp')
    with temporary.open('w') as stream:
        json.dump(value, stream, ensure_ascii=False, indent=2)
        stream.write('\n'); stream.flush(); os.fsync(stream.fileno())
    temporary.replace(path)
    fd = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def data_state(store):
    result = {}
    for suffix, path in segment_files(store).items():
        stat = path.stat()
        pages = []
        with path.open('rb') as stream:
            for page in iter(lambda: stream.read(16384), b''):
                pages.append(hashlib.sha256(page).hexdigest())
        result[suffix] = dict(device=stat.st_dev, inode=stat.st_ino, bytes=stat.st_size,
                              sha256=sha(path), page_sha256=pages)
    return result


def snapshot_counts(store):
    data = Path(str(store) + '.snapshot').read_bytes()
    _, offset = parse_segment_layout(data, 16)
    offset += 10 * 8  # six allocator fields, four root references
    def take(count=1):
        nonlocal offset
        require(offset + count * 8 <= len(data), 'truncated checkpoint index')
        values = struct.unpack_from('<' + 'Q' * count, data, offset)
        offset += count * 8
        return values[0] if count == 1 else values
    def index():
        nonlocal offset
        state, head, depth, files, single, slots = take(6)
        require(state <= 2 and depth <= 20, 'invalid checkpoint index state')
        require(slots == ((1 << depth) if state == 2 else 0), 'invalid index slot count')
        offset += slots * 8
        buckets = take()
        count = 0
        for _ in range(buckets):
            block, local_depth, entries, version, flags = take(5)
            require(block and local_depth <= depth, 'invalid bucket in checkpoint')
            count += entries
        require(count == files, 'bucket count and file count differ')
        return files, buckets
    files, buckets = index()
    directories = 1
    def records():
        nonlocal files, buckets, directories
        while True:
            depth = take()
            if depth == (1 << 64) - 1:
                break
            take(3)
            new_files, new_buckets = index()
            files += new_files; buckets += new_buckets; directories += 1
        take()  # checksum was independently checked by assert_snapshot_files
        require(offset == len(data), 'checkpoint has trailing data')
    if struct.unpack_from('<Q', data, 8)[0] == 5:
        for entry in checkpoint_indexes(store):
            data = Path(entry['path']).read_bytes(); offset = 16
            records()
    else:
        records()
    return dict(files=files, directories=directories, buckets=buckets)


def expected_queries():
    values = {}
    for copy in range(1, 4):
        prefix = f'/copy-{copy:06d}'
        first_page = 6 + (copy - 1) * 477
        first_head = 32 + (copy - 1) * 194 * 31
        first_bucket = (copy - 1) * 500
        ordinals = {0, 59, 60, 29999}
        for boundary in range((first_page // PAGES + 1) * PAGES, first_page + 477, PAGES):
            edge = (boundary - first_page) * 63
            ordinals.update(n for n in range(edge - 2, edge + 3) if 0 <= n < 30000)
        for boundary in range((first_bucket // PAGES + 1) * PAGES, first_bucket + 500, PAGES):
            edge = (boundary - first_bucket) * 60
            ordinals.update(n for n in range(edge - 2, edge + 3) if 0 <= n < 30000)
        for ordinal in ordinals:
            path = f'{prefix}/d{ordinal//60:05d}/f{ordinal%60:03d}'
            values[path] = dict(size=1000+ordinal, mtime=123, mode=0o644,
                                inode_id=((first_page + ordinal // 63) << 16) | (ordinal % 63),
                                type=0)
        heads = {0, 1, 5999}
        for boundary in range(1, 3):
            edge = boundary * PAGES * 31 + 1 - first_head - 1
            heads.update(n for n in range(edge - 2, edge + 3) if 0 <= n < 6000)
        values[prefix] = dict(size=0, mode=0o755, type=1,
                              inode_id=(1 << 63) | (1 << 47) | first_head)
        for index in heads:
            values[f'{prefix}/d{index:05d}'] = dict(size=0, mode=0o755, type=1,
                inode_id=(1 << 63) | (1 << 47) | (first_head + index + 1))
    return values


def main():
    global WORK_DIR
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--server', type=Path, required=True)
    parser.add_argument('--library', type=Path, required=True)
    parser.add_argument('--testing-library', type=Path, required=True)
    parser.add_argument('--template', type=Path, required=True)
    parser.add_argument('--work-dir', type=Path, required=True)
    default_runner = Path(__file__).resolve().parent / 'import_lhm_batches.py'
    if not default_runner.is_file():
        default_runner = Path(__file__).resolve().parents[2] / 'scripts/import_lhm_batches.py'
    parser.add_argument('--batch-runner', type=Path, default=default_runner)
    args = parser.parse_args()
    for name in ('server', 'library', 'testing_library', 'batch_runner'):
        require(getattr(args, name).is_file(), 'missing input: ' + name)
    require(b'ZB_LHM_CRASH_AT' not in args.library.read_bytes(), 'production library contains test fault injection')
    require(b'ZB_LHM_TEST_SEGMENT_BYTES' in args.testing_library.read_bytes(), 'testing library lacks small segments')
    require((args.template / 'inode.pages').stat().st_size == 477 * 16384 and
            (args.template / 'heads.pages').stat().st_size == 194 * 16384 and
            (args.template / 'bucket.pages').stat().st_size == 500 * 16384,
            'expected the 30,000-file / 6,001-directory segmented test bundle')
    work = args.work_dir.resolve()
    work.mkdir(parents=True, exist_ok=False)
    WORK_DIR = work
    runtime, logs = work / 'runtime', work / 'logs'
    runtime.mkdir(); logs.mkdir()
    for name in ('production', 'testing'):
        (runtime / name).mkdir()
    shutil.copy2(args.server, runtime / 'mds_server')
    shutil.copy2(args.library, runtime / 'production/libzb_lhm_bridge.so')
    shutil.copy2(args.testing_library, runtime / 'testing/libzb_lhm_bridge.so')
    shutil.copy2(args.batch_runner, runtime / 'import_lhm_batches.py')
    shutil.copy2(__file__, runtime / Path(__file__).name)
    shutil.copy2(Path(__file__).with_name('lhm_batch_recovery_test.py'), runtime / 'lhm_batch_recovery_test.py')
    shutil.copytree(args.template, runtime / 'compiled')
    store = work / 'namespace.meta'
    library = runtime / 'production/libzb_lhm_bridge.so'
    testing = runtime / 'testing/libzb_lhm_bridge.so'
    fingerprints = {str(path.relative_to(runtime)): sha(path) for path in runtime.rglob('*') if path.is_file()}
    save(work / 'runtime-sha256.json', fingerprints)
    evidence, processes = [], []
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

    def rpc(port, method, body):
        request = urllib.request.Request(f'http://127.0.0.1:{port}/zb.rpc.MdsService/{method}',
            data=json.dumps(body).encode(), headers={'Content-Type': 'application/json'})
        with opener.open(request, timeout=60) as response:
            value = json.load(response)
        evidence.append(dict(method=method, request=body, response=value))
        require(value.get('status', {}).get('code', 0) in (0, 'MDS_OK'), 'RPC failed: ' + str(value))
        return value

    def serve(mode, linked_library, action):
        config = work / f'mds-{mode}.conf'
        config.write_text(f'MDS_DB_PATH={work}/control\nNAMESPACE_BACKEND=lhm\n'
            f'LHM_STORE_FILE={store}\nLHM_STORE_MODE={mode}\nMASSTREE_ROOT={work}/templates\n'
            'ENABLE_OPTICAL_ARCHIVE=false\nMASSTREE_PRELOAD_ALL_SPARSE_ON_START=false\n'
            'NODES=node-real-01@127.0.0.1:9100\nDISKS=node-real-01:disk-01\nREPLICA=1\nPG_COUNT=16\n')
        with socket.socket() as probe:
            probe.bind(('127.0.0.1', 0)); port = probe.getsockname()[1]
        environment = os.environ.copy()
        environment.pop('ZB_LHM_CRASH_AT', None); environment.pop('ZB_LHM_TEST_SEGMENT_BYTES', None)
        environment['LD_LIBRARY_PATH'] = str(linked_library.parent) + (
            ':' + environment['LD_LIBRARY_PATH'] if environment.get('LD_LIBRARY_PATH') else '')
        if mode == 'create':
            environment['ZB_LHM_TEST_SEGMENT_BYTES'] = str(SEGMENT_BYTES)
        command = [str(runtime / 'mds_server'), '--config=' + str(config), '--port=' + str(port)]
        with (logs / f'mds-{mode}.log').open('w') as output:
            proc = subprocess.Popen(command, cwd=work, env=environment, stdin=subprocess.DEVNULL,
                                    stdout=output, stderr=subprocess.STDOUT, start_new_session=True)
            info = dict(mode=mode, pid=proc.pid, port=port, library=str(linked_library), command=command)
            processes.append(info); save(work / 'processes.json', processes)
            try:
                deadline = time.monotonic() + 90
                while True:
                    require(proc.poll() is None, f'MDS {mode} exited early; see {output.name}')
                    try:
                        with socket.create_connection(('127.0.0.1', port), timeout=.2):
                            break
                    except OSError:
                        require(time.monotonic() < deadline, 'MDS startup timed out')
                        time.sleep(.1)
                require(str(linked_library) in Path(f'/proc/{proc.pid}/maps').read_text(),
                        'MDS loaded an unpinned or wrong bridge')
                action(port)
            finally:
                if proc.poll() is None:
                    proc.terminate()
                try:
                    code = proc.wait(timeout=90)
                except subprocess.TimeoutExpired:
                    proc.kill(); proc.wait()
                    raise RuntimeError('MDS normal shutdown timed out')
                info['exit_code'] = code; save(work / 'processes.json', processes)
                save(work / 'rpc-evidence.json', evidence)
            require(code == 0, 'MDS normal shutdown failed')

    started = time.monotonic()
    serve('create', testing, lambda port: require(not rpc(port, 'Readdir', dict(path='/', limit=1)).get('entries'),
                                                'fresh MDS root was not empty'))
    require(assert_snapshot_files(store)['segment_bytes'] == SEGMENT_BYTES,
            'testing MDS did not persist 8 MiB segments')
    command = [sys.executable, str(runtime / 'import_lhm_batches.py'), 'import', '--store', str(store),
        '--compiled-template', str(runtime / 'compiled'), '--library', str(library), '--prefix', '/copy',
        '--copies', '3', '--min-free-gib', '0', '--expected-files', '30000', '--expected-directories', '6001',
        '--log', str(logs / 'batches.jsonl')]
    with (logs / 'import.log').open('w') as output:
        imported = subprocess.run(command, cwd=work, stdin=subprocess.DEVNULL, stdout=output,
                                  stderr=subprocess.STDOUT, timeout=180)
    require(imported.returncode == 0, 'production offline import failed; see logs/import.log')
    layout = assert_snapshot_files(store)
    require(layout['segment_bytes'] == SEGMENT_BYTES, 'production import changed persisted segment size')
    require(all(sum(s['kind'] == kind for s in layout['segments']) >= 2 for kind in range(3)),
            'not all data kinds crossed a segment')
    counts = snapshot_counts(store)
    require(counts == dict(files=90000, directories=18004, buckets=1500), 'exact checkpoint counts differ')
    snapshot_hash = sha(Path(str(store) + '.snapshot'))
    receipt = Path(str(store) + '.batch-receipt').read_bytes()
    before = data_state(store)
    save(work / 'before-reopen.json', dict(segments=before, snapshot_sha256=snapshot_hash,
        receipt_sha256=hashlib.sha256(receipt).hexdigest()))
    expected = expected_queries()
    inode_ids = set()

    def check(port):
        for path, fields in sorted(expected.items()):
            attr = rpc(port, 'Lookup', dict(path=path))['attr']
            for name, value in fields.items():
                actual = attr.get(name, 0)
                if name == 'type' and isinstance(actual, str):
                    actual = {'INODE_FILE': 0, 'INODE_DIR': 1}[actual]
                require(int(actual) == value, f'RPC {name} differs: {path}')
            inode = int(attr['inode_id'])
            require(inode not in inode_ids, 'RPC returned duplicate inode IDs across paths')
            inode_ids.add(inode)
            require(rpc(port, 'Getattr', dict(inode_id=str(inode)))['attr'] == attr,
                    'RPC Lookup and Getattr differ')
        for path, names, limit in (
            ('/', [f'copy-{i:06d}' for i in range(1, 4)], 1),
            ('/copy-000003/d00024', [f'f{i:03d}' for i in range(60)], 17)):
            found, after = [], ''
            while True:
                value = rpc(port, 'Readdir', dict(path=path, start_after=after, limit=limit))
                entries = value.get('entries', [])
                found += [entry['name'] for entry in entries]
                if not value.get('has_more', False):
                    break
                following = value.get('next_token', '')
                require(entries and following and following != after, 'RPC pagination failed to advance')
                after = following
            require(len(found) == len(set(found)) and set(found) == set(names),
                    'RPC Readdir omitted or duplicated entries')

    serve('reopen', library, check)
    after = data_state(store)
    save(work / 'after-reopen.json', dict(segments=after,
        snapshot_sha256=sha(Path(str(store) + '.snapshot')),
        receipt_sha256=sha(Path(str(store) + '.batch-receipt'))))
    # Query-only startup now reads the existing root. Every page, including the
    # root, must remain byte-identical, with unchanged identities and lengths.
    require(after.keys() == before.keys(), 'MDS changed the segment set')
    changed_pages = []
    for suffix in before:
        for key in ('device', 'inode', 'bytes'):
            require(before[suffix][key] == after[suffix][key], 'MDS changed a segment ' + key)
        for page, (old, new) in enumerate(zip(before[suffix]['page_sha256'], after[suffix]['page_sha256'])):
            if old != new:
                require(False, 'read-only MDS changed a data page')
                changed_pages.append(dict(segment=suffix, page=page))
    require(sha(Path(str(store) + '.snapshot')) == snapshot_hash, 'read-only MDS changed snapshot bytes')
    require(Path(str(store) + '.batch-receipt').read_bytes() == receipt, 'read-only MDS changed receipt')
    assert_snapshot_files(store)
    checked = subprocess.run([sys.executable, str(runtime / 'import_lhm_batches.py'), 'status',
        '--store', str(store), '--library', str(library)], capture_output=True, text=True, timeout=60)
    (logs / 'final-status.log').write_text(checked.stdout + checked.stderr)
    require(checked.returncode == 0, 'final production checkpoint status failed')
    save(work / 'rpc-evidence.json', evidence)
    report = dict(status='passed', store=str(store), segment_bytes=SEGMENT_BYTES, copies=3,
        counts=counts, queried_paths=len(expected), unique_sampled_inodes=len(inode_ids),
        rpc_calls=len(evidence),
        rpc_method_counts={method: sum(item['method'] == method for item in evidence)
                           for method in ('Lookup', 'Getattr', 'Readdir')},
        segment_counts={str(kind): sum(s['kind'] == kind for s in layout['segments'])
                                               for kind in range(3)},
        snapshot_unchanged=True, receipt_unchanged=True, imported_pages_unchanged=True,
        root_pages_refreshed_on_start=changed_pages,
        testing_library_used_only_for_initialization=True,
        production_library_sha256=sha(library), testing_library_sha256=sha(testing),
        elapsed_seconds=round(time.monotonic()-started, 3),
        completed_at=datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=8))).isoformat(),
        processes=processes)
    save(work / 'result.json', report)
    print(json.dumps(report, ensure_ascii=False), flush=True)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except Exception as error:
        if WORK_DIR is not None:
            save(WORK_DIR / 'result.json', dict(status='failed', error=str(error)))
        print('FAIL: ' + str(error), file=sys.stderr)
        sys.exit(1)
